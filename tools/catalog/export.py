"""Catalog exporter: tools/catalog/catalog.json -> data/**/*.tres.

    python3 -m tools.catalog.export           # write data/ and tools/catalog/pending.txt
    python3 -m tools.catalog.export --check   # fail if data/ is not what the catalog gives

Exit code 1 on any error: a cell that does not parse, a reference to a missing building,
unit or caster, an empty required cell, or a prototype unit with a rule the exporter does
not understand. Rules of non-prototype units that are not understood yet are listed in
pending.txt; they become errors once the unit enters the prototype.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import tres
from .model import KIND_DIRS, SCHEMAS, Builder, Report

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
DATA_DIR = ROOT / "data"
PENDING_PATH = HERE / "pending.txt"


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def build(catalog: dict, manual: dict | None = None, prototype: dict | None = None):
    builder = Builder(
        catalog,
        manual if manual is not None else load_json(HERE / "manual.json"),
        prototype if prototype is not None else load_json(HERE / "prototype.json"),
    )
    defs = builder.build()
    return defs, builder.index(), builder.rep


def render_files(defs: dict, index: dict, rep: Report) -> dict[str, str]:
    """Relative path -> file text, for everything the exporter owns."""
    files: dict[str, str] = {}
    for kind, items in defs.items():
        for eid, data in items.items():
            files[f"data/{KIND_DIRS[kind]}/{eid}.tres"] = tres.render(kind, SCHEMAS[kind], data)
    files["data/catalog_index.tres"] = tres.render("CatalogIndex", SCHEMAS["CatalogIndex"], index)
    header = (
        "# Rules from «Особое» the exporter does not understand yet (non-prototype units).\n"
        "# Generated by tools/catalog/export.py; a rule moves out of here when it gets a parser.\n"
    )
    files["tools/catalog/pending.txt"] = header + "".join(f"{p}\n" for p in sorted(rep.pending))
    return files


def owned_paths(root: Path) -> set[str]:
    """Files under the exporter's control that exist on disk now."""
    found = {str(p.relative_to(root)) for d in KIND_DIRS.values() for p in (root / "data" / d).glob("*.tres")}
    for extra in ("data/catalog_index.tres", "tools/catalog/pending.txt"):
        if (root / extra).exists():
            found.add(extra)
    return found


def write(files: dict[str, str], root: Path) -> None:
    for stale in owned_paths(root) - set(files):
        (root / stale).unlink()
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")


def check(files: dict[str, str], root: Path) -> list[str]:
    problems = []
    on_disk = owned_paths(root)
    for rel in sorted(on_disk - set(files)):
        problems.append(f"stale file: {rel}")
    for rel, text in sorted(files.items()):
        path = root / rel
        if not path.exists():
            problems.append(f"missing file: {rel}")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"differs from catalog: {rel}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="compare with data/ instead of writing")
    parser.add_argument("--catalog", type=Path, default=HERE / "catalog.json")
    parser.add_argument("--root", type=Path, default=ROOT, help="project root to write into")
    args = parser.parse_args(argv)

    defs, index, rep = build(load_json(args.catalog))
    for err in rep.errors:
        print(f"ERROR: {err}", file=sys.stderr)
    if rep.errors:
        print(f"{len(rep.errors)} error(s); nothing written.", file=sys.stderr)
        return 1
    files = render_files(defs, index, rep)
    if args.check:
        problems = check(files, args.root)
        for p in problems:
            print(f"ERROR: {p}", file=sys.stderr)
        if problems:
            print("Run `python3 -m tools.catalog.export` and commit the result.", file=sys.stderr)
            return 1
        print(f"data/ matches the catalog ({len(files)} files).")
        return 0
    write(files, args.root)
    counts = ", ".join(f"{len(v)} {KIND_DIRS[k]}" for k, v in defs.items())
    print(f"Exported {counts}; {len(rep.pending)} rule(s) pending, see {PENDING_PATH.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
